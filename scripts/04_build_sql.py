"""Generate sql/02_load_data.sql from the cleaned/processed CSVs.

No value is typed by hand: SQL and CSV cannot diverge. Re-run after any change to
data/cleaned/*.csv (and after scripts/02_validate_and_derive.py).
"""
import pandas as pd
from config import CLEANED_DIR, PROCESSED_DIR, SQL_DIR

def lit(v):
    if pd.isna(v):
        return "NULL"
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    return repr(round(float(v), 4)).rstrip("0").rstrip(".") if not float(v).is_integer() else str(int(v))

ann = pd.read_csv(PROCESSED_DIR / "annual_national_full.csv")
tr = pd.read_csv(CLEANED_DIR / "country_trade.csv")

acols = [("fiscal_year", "fiscal_year"), ("fiscal_year_label", "fiscal_year_label"),
         ("nea_generation_gwh", "nea_generation_gwh"), ("ipp_purchase_gwh", "ipp_purchase_gwh"),
         ("total_production_gwh", "total_production_gwh"), ("import_gwh", "import_gwh"),
         ("export_gwh", "export_gwh"), ("net_export_gwh", "net_export_gwh"),
         ("total_available_gwh", "total_available_gwh"), ("domestic_consumption_gwh", "domestic_consumption_gwh"),
         ("peak_demand_mw", "peak_demand_mw"), ("peak_supply_mw", "peak_supply_mw"),
         ("ppa_signed_capacity_mw", "ppa_signed_capacity_mw"),
         ("revenue_npr_million", "nea_revenue_npr_million"), ("cost_npr_million", "nea_cost_npr_million"),
         ("profit_npr_million", "nea_profit_npr_million"), ("profit_margin_pct", "nea_profit_margin_pct"),
         ("system_loss_pct", "system_loss_pct"), ("consumers_million", "consumers_million"),
         ("source_report", "source_report")]
tcols = ["fiscal_year", "country", "trade_status", "trade_partner", "trade_mechanism", "export_gwh",
         "import_gwh", "export_revenue_npr_million", "import_cost_npr_million", "export_capacity_mw",
         "import_capacity_mw", "season_active", "volume_scope", "notes", "data_source"]

out = ["-- GENERATED by scripts/04_build_sql.py - do not edit by hand.",
       "-- Source: data/processed/annual_national_full.csv, data/cleaned/country_trade.csv", ""]
out.append(f"INSERT INTO nea_annual_data ({', '.join(c[1] for c in acols)}) VALUES")
out.append(",\n".join("(" + ", ".join(lit(r[c[0]]) for c in acols) + ")" for _, r in ann.iterrows()) + ";")
out.append("")
out.append(f"INSERT INTO nea_country_trade ({', '.join(tcols)}) VALUES")
out.append(",\n".join("(" + ", ".join(lit(r[c]) for c in tcols) + ")" for _, r in tr.iterrows()) + ";")
out.append("")
out.append("SELECT 'nea_annual_data' AS table_name, COUNT(*) AS n FROM nea_annual_data\nUNION ALL SELECT 'nea_country_trade', COUNT(*) FROM nea_country_trade;")
(SQL_DIR / "02_load_data.sql").write_text("\n".join(out) + "\n")
print("wrote sql/02_load_data.sql", len(ann), "annual rows,", len(tr), "trade rows")
