# =============================================================================
# PROJECT  : NEA Nepal — Annual Energy & Financial Dataset
# AUTHOR   : Riyam Kafle
# SOURCE   : NEA Annual Reports FY 2019/20 → FY 2024/25
# OUTPUT   : NEA_Raw_Data.xlsx (5 sheets) + NEA_Raw_Data.csv
# =============================================================================
# ABOUT THIS SCRIPT
# -----------------
# This script takes the verified data manually extracted from 6 NEA Annual
# Report PDFs and organizes it into a clean, structured dataset.
#
# The Fiscal_Year column uses Gregorian end-year format:
#   2020 = FY 2019/20
#   2021 = FY 2020/21  ... and so on
#
# All values are sourced DIRECTLY from PDF text — nothing is assumed.
# If a value could not be found in any PDF, it is left as NULL (None).
# =============================================================================

import pandas as pd
from pathlib import Path

# -----------------------------------------------------------------------------
# STEP 1: SET UP OUTPUT FOLDER
# Where our final Excel and CSV files will be saved
# -----------------------------------------------------------------------------
OUTPUT_DIR = Path.home() / "Desktop/NEA_Projects/data/output"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
print(f"📁 Output folder ready → {OUTPUT_DIR}")


# -----------------------------------------------------------------------------
# STEP 2: DEFINE THE DATASET
# Each list represents one column across 6 fiscal years (2020 → 2025)
# All energy values are in GWh, demand in MW, financials in Million NPR
# -----------------------------------------------------------------------------
data = {

    # Gregorian end-year of Nepal fiscal year
    # 2020 = FY 2019/20 | 2021 = FY 2020/21 | 2022 = FY 2021/22
    # 2023 = FY 2022/23 | 2024 = FY 2023/24 | 2025 = FY 2024/25
    "Fiscal_Year" : [2020, 2021, 2022, 2023, 2024, 2025],

    # Electricity generated by NEA's own hydropower plants (GWh)
    # Source: Generation Directorate section of each annual report
    "NEA_Generation_GWh" : [3021.06, 2810.74, 3259.00, 2930.00, 2911.00, 2953.00],

    # Electricity purchased from Independent Power Producers (GWh)
    # 2020-2021: Nepal-based IPPs only (no subsidiary category yet)
    # 2022-2025: Includes NEA subsidiaries + IPPs combined
    "IPP_Purchase_GWh" : [2991.00, 3241.00, 6262.00, 7606.00, 9161.00, 11006.00],

    # Total domestic production = NEA generation + IPP purchase
    # Does NOT include electricity imported from India
    "Total_Production_GWh" : [6012.06, 6051.74, 9521.00, 10536.00, 12072.00, 13959.00],

    # Electricity imported from India during dry season
    # Source: Managing Director's Report — Energy section
    "Import_GWh" : [1729.00, 2826.21, 1543.00, 1833.00, 1895.00, 1681.00],

    # Electricity exported to India
    # Source: Managing Director's Report — Energy section
    "Export_GWh" : [107.00, 44.00, 493.00, 1346.00, 1946.00, 2380.00],

    # Total electricity consumed inside Nepal (excluding exports)
    # Source: "Internal Sold/Utilized (GWh)" from Highlights table
    "Domestic_Consumption_GWh" : [6422.00, 7275.00, 8870.00, 9358.00, 10243.00, 11343.00],

    # Highest electricity demand recorded during the fiscal year (MW)
    # Source: Transmission/Load Dispatch section of each report
    "Peak_Demand_MW" : [1407.94, 1482.00, 1747.53, 1870.46, 2211.62, 2409.00],

    # Maximum supply available at time of peak demand (MW)
    # 2020: NULL — not separately reported in 2019-20 annual report
    "Peak_Supply_MW" : [None, 1481.85, 1963.98, 2171.15, 2467.00, 2901.00],

    # Total revenue earned by NEA from electricity sales + other income (M.NPR)
    # Source: Finance Directorate — Revenue section
    # Note: 2020 uses own-year figure (73,760M), not the restated figure
    "Revenue_NPR_Million" : [73760.00, 76726.00, 87120.00, 100032.00, 115798.00, 125277.00],

    # Total cost = Revenue - Net Profit Before Tax
    # Derived this way for consistency because P&L format changed in 2021-22
    # Covers: power purchase + generation + transmission + distribution + admin
    "Cost_NPR_Million" : [62704.00, 70718.00, 70955.00, 87639.00, 102491.00, 116210.00],

    # Net Profit Before Tax (M.NPR)
    # Source: Finance Directorate — Profit & Loss section
    # Post-tax figure NOT used — kept consistent across all years
    "Profit_NPR_Million" : [11056.00, 6008.00, 16165.00, 12393.00, 13307.00, 9067.00],
}

# Build the DataFrame
df = pd.DataFrame(data)
print(f"✅ Dataset created → {df.shape[0]} rows x {df.shape[1]} columns")


# -----------------------------------------------------------------------------
# STEP 3: ADD DERIVED COLUMNS
# These are calculated from existing columns- no assumptions
# -----------------------------------------------------------------------------

# Net Export = how much more we exported than imported
# Positive = net exporter | Negative = net importer
df["Net_Export_GWh"] = df["Export_GWh"] - df["Import_GWh"]

# Total Available Energy = all energy in the national grid
# = Domestic production + Imports from India
df["Total_Available_GWh"] = df["Total_Production_GWh"] + df["Import_GWh"]

# Profit Margin = what percentage of revenue became profit
df["Profit_Margin_Pct"] = (
    df["Profit_NPR_Million"] / df["Revenue_NPR_Million"] * 100
).round(2)

print("✅ Derived columns added → Net_Export_GWh, Total_Available_GWh, Profit_Margin_Pct")


# -----------------------------------------------------------------------------
# STEP 4: PRINT THE FULL DATASET TO TERMINAL
# So we can visually verify everything looks correct
# -----------------------------------------------------------------------------
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 250)
pd.set_option("display.float_format", "{:,.2f}".format)

print("\n" + "=" * 80)
print("   NEA NEPAL — COMPLETE ENERGY DATASET   |   2020 → 2025 (Gregorian)")
print("=" * 80)
print(df.to_string(index=False))

# Show missing value summary
print("\n── MISSING VALUE REPORT ──")
missing = df.isnull().sum()
missing = missing[missing > 0]
if len(missing) > 0:
    print("  Columns with NULL values (genuine — not found in any PDF):")
    for col, count in missing.items():
        print(f"    {col:35s} → {count} out of {len(df)} years")
else:
    print("  ✅ No missing values!")


# -----------------------------------------------------------------------------
# STEP 5: EXPORT TO EXCEL
# 5 sheets: All Data | Energy | Demand | Financials | Data Quality Notes
# -----------------------------------------------------------------------------
excel_path = OUTPUT_DIR / "NEA_Raw_Data.xlsx"

with pd.ExcelWriter(excel_path, engine="openpyxl") as writer:

    # ── Sheet 1: All Data ──────────────────────────────────────────────
    # The complete dataset with every column
    df.to_excel(writer, sheet_name="All_Data", index=False)
    ws = writer.sheets["All_Data"]
    for col in ws.columns:
        max_len = max(len(str(cell.value or "")) for cell in col) + 3
        ws.column_dimensions[col[0].column_letter].width = min(max_len, 28)

    # ── Sheet 2: Energy GWh ───────────────────────────────────────────
    # All generation, import, export and consumption figures
    energy_cols = [
        "Fiscal_Year",
        "NEA_Generation_GWh",
        "IPP_Purchase_GWh",
        "Total_Production_GWh",
        "Import_GWh",
        "Export_GWh",
        "Net_Export_GWh",
        "Total_Available_GWh",
        "Domestic_Consumption_GWh",
    ]
    df[energy_cols].to_excel(writer, sheet_name="Energy_GWh", index=False)
    ws2 = writer.sheets["Energy_GWh"]
    for col in ws2.columns:
        max_len = max(len(str(cell.value or "")) for cell in col) + 3
        ws2.column_dimensions[col[0].column_letter].width = min(max_len, 28)

    # ── Sheet 3: Demand MW ────────────────────────────────────────────
    # Peak demand and supply figures
    demand_cols = [
        "Fiscal_Year",
        "Peak_Demand_MW",
        "Peak_Supply_MW",
        "Domestic_Consumption_GWh",
    ]
    df[demand_cols].to_excel(writer, sheet_name="Demand_MW", index=False)
    ws3 = writer.sheets["Demand_MW"]
    for col in ws3.columns:
        max_len = max(len(str(cell.value or "")) for cell in col) + 3
        ws3.column_dimensions[col[0].column_letter].width = min(max_len, 28)

    # ── Sheet 4: Financials NPR ───────────────────────────────────────
    # Revenue, cost, profit and margin
    fin_cols = [
        "Fiscal_Year",
        "Revenue_NPR_Million",
        "Cost_NPR_Million",
        "Profit_NPR_Million",
        "Profit_Margin_Pct",
    ]
    df[fin_cols].to_excel(writer, sheet_name="Financials_NPR", index=False)
    ws4 = writer.sheets["Financials_NPR"]
    for col in ws4.columns:
        max_len = max(len(str(cell.value or "")) for cell in col) + 3
        ws4.column_dimensions[col[0].column_letter].width = min(max_len, 28)

    # ── Sheet 5: Data Quality Notes ───────────────────────────────────
    # Explains every data decision, source, and known limitation
    notes = pd.DataFrame({
        "Field": [
            "Fiscal_Year column",
            "Peak_Supply_MW — 2020",
            "IPP_Purchase_GWh — 2020 and 2021",
            "IPP_Purchase_GWh — 2022 onwards",
            "Cost_NPR_Million — all years",
            "Revenue_NPR_Million — 2020",
            "Profit_NPR_Million — all years",
            "Total_Production_GWh",
            "Domestic_Consumption_GWh",
            "Net_Export_GWh",
            "Total_Available_GWh",
        ],
        "Status": [
            "NOTE",
            "NULL",
            "VERIFIED",
            "VERIFIED",
            "DERIVED",
            "NOTE",
            "VERIFIED",
            "VERIFIED",
            "VERIFIED",
            "DERIVED",
            "DERIVED",
        ],
        "Source / Explanation": [
            "Gregorian end-year. 2020=FY2019/20, 2021=FY2020/21, 2022=FY2021/22, 2023=FY2022/23, 2024=FY2023/24, 2025=FY2024/25",
            "Not reported in 2019-20 annual report. Get from NEA Statistics Book at nea.org.np",
            "No NEA Subsidiary category existed yet. IPP = Nepal-based independent producers only.",
            "IPP_Purchase includes NEA Subsidiaries + Nepal-based IPPs combined for year-on-year consistency.",
            "Derived as Revenue - Profit. Used because P&L statement format changed between 2020-21 and 2021-22.",
            "Own-year report shows 73,760M NPR. The 2020-21 report restates this as 76,076M (audit revision). Own-year used.",
            "Net Profit Before Tax. Post-tax figure not used to keep all years consistent.",
            "NEA own generation + IPP purchase only. India imports are excluded (tracked separately as Import_GWh).",
            "Internal sold/utilized GWh from Highlights table. Excludes electricity exported to India.",
            "Calculated: Export_GWh - Import_GWh. Positive = net exporter. Negative = net importer.",
            "Calculated: Total_Production_GWh + Import_GWh. Represents all energy available in national grid.",
        ],
    })
    notes.to_excel(writer, sheet_name="Data_Quality_Notes", index=False)
    ws5 = writer.sheets["Data_Quality_Notes"]
    ws5.column_dimensions["A"].width = 38
    ws5.column_dimensions["B"].width = 12
    ws5.column_dimensions["C"].width = 85

print(f"\n✅ Excel saved  → {excel_path}")
print(f"   Sheets: All_Data | Energy_GWh | Demand_MW | Financials_NPR | Data_Quality_Notes")


# -----------------------------------------------------------------------------
# STEP 6: EXPORT TO CSV
# Flat single-sheet file — ready for Power BI, Tableau, or Python analysis
# -----------------------------------------------------------------------------
csv_path = OUTPUT_DIR / "NEA_Raw_Data.csv"
df.to_csv(csv_path, index=False)
print(f"✅ CSV saved    → {csv_path}")


# -----------------------------------------------------------------------------
# STEP 7: CONFIRM WHAT WAS SAVED
# List all files in the output folder with their sizes
# -----------------------------------------------------------------------------
print("\n── FILES IN OUTPUT FOLDER ──")
for f in sorted(OUTPUT_DIR.glob("*")):
    size_kb = f.stat().st_size / 1024
    print(f"   📄 {f.name:45s} {size_kb:.1f} KB")

print("\n🎉 EXTRACTION COMPLETE! Your data is ready.")